#!/usr/bin/env bash
# Regenerate the list of every item in the game (data/tech-tree/60-items-full.yaml).
#
# The item definitions and their anchors live in the 30-item-* files, and each
# age/category is linked in with an anchor. This script harvests those anchors and
# writes them out as items: references, keeping the group comments of each source
# file. Run it after adding, removing or renaming an item, then run data/build.sh.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd -- "${SCRIPT_DIR}/.." && pwd)"
DATA_DIR="${ROOT_DIR}/data/tech-tree"
DEST="${DATA_DIR}/60-items-full.yaml"

# Write the anchors of one item file as references, with its group comments.
emit_items() {
    local file="$1"
    local header=""
    local line

    while IFS= read -r line; do
        if [[ "${line}" =~ ^#[[:space:]]+(.+) ]]; then
            # The first unindented comment names the group of the file.
            if [[ -z "${header}" ]]; then
                header="  # ${BASH_REMATCH[1]}"
                echo "${header}"
            fi
        elif [[ "${line}" =~ ^[[:space:]]+#[[:space:]]+(.+) ]]; then
            echo "  # ${BASH_REMATCH[1]}"
        elif [[ "${line}" =~ ^[[:space:]]+-[[:space:]]+item:[[:space:]]+\&(item[A-Za-z0-9]+)[[:space:]]*$ ]]; then
            echo "  - item:"
            echo "      <<: *${BASH_REMATCH[1]}"
        fi
    done < "${file}"
}

{
    echo "---"
    echo "# Every item in the game. The item definitions and their anchors live in"
    echo "# the 30-item-* files; this list just selects them."
    echo "#"
    echo "# Generated by Scripts/GenerateItemList.sh - edit the 30-item-* files instead."
    echo "items:"

    for file in "${DATA_DIR}"/30-item-*.yaml; do
        echo
        emit_items "${file}"
    done
} > "${DEST}.tmp"

count="$(grep -c '<<: \*' "${DEST}.tmp" || true)"
mv "${DEST}.tmp" "${DEST}"

echo "Wrote ${count} item references to ${DEST}"
